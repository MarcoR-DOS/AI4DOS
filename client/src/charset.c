static const unsigned short *table_for(unsigned cp)
{return cp==437?cp437:cp==850?cp850:0;}
int dos_to_utf8(const char *src,char *dst,unsigned capacity,unsigned codepage)
{
    const unsigned short *table=table_for(codepage);
    const unsigned char *p=(const unsigned char *)src;
    unsigned out=0,cp,n;unsigned char ch;
    if(!capacity)return -1;
    while((ch=*p++)!=0){
        if(ch<32||ch==127){dst[0]=0;return -1;}
        cp=ch<128?ch:table?table[ch-128]:'?';
        n=cp<128?1U:cp<2048?2U:3U;
        if(n>=capacity-out){dst[0]=0;return -1;}
        if(n==1)dst[out++]=(char)cp;
        else if(n==2){dst[out++]=(char)(0xc0|(cp>>6));dst[out++]=(char)(0x80|(cp&63));}
        else{dst[out++]=(char)(0xe0|(cp>>12));dst[out++]=(char)(0x80|((cp>>6)&63));dst[out++]=(char)(0x80|(cp&63));}
    }
    dst[out]=0;return (int)out;
}
static unsigned char dos_for(unsigned long cp,unsigned codepage)
{
    const unsigned short *table=table_for(codepage);unsigned i;
    if(cp<128)return (unsigned char)cp;
    if(table)for(i=0;i<128;++i)if(table[i]==cp)return (unsigned char)(i+128);
    switch(cp){
    case 0x2018UL:case 0x2019UL:case 0x201aUL:return '\'';
    case 0x201cUL:case 0x201dUL:case 0x201eUL:return '"';
    case 0x2013UL:case 0x2014UL:case 0x2212UL:return '-';
    case 0x2022UL:return '*';
    case 0xa0UL:return ' ';
    default:return '?';
    }
}
unsigned utf8_to_dos(const char *src,char *dst,unsigned capacity,unsigned codepage)
{
    const unsigned char *p=(const unsigned char *)src;
    unsigned out=0,need,i;unsigned long cp;
    if(!capacity)return 0;
    while(*p&&out+1<capacity){
        if(*p<128){
            if(*p=='\n'||*p=='\t'||(*p>=32&&*p!=127))dst[out++]=(char)*p;
            ++p;continue;
        }
        if((*p&0xe0)==0xc0){cp=*p&31;need=*p>=0xc2?1U:0;}
        else if((*p&0xf0)==0xe0){cp=*p&15;need=2;}
        else if((*p&0xf8)==0xf0){cp=*p&7;need=3;}
        else{dst[out++]='?';++p;continue;}
        if(!need){dst[out++]='?';++p;continue;}
        for(i=1;i<=need;++i){if(!p[i]||(p[i]&0xc0)!=0x80)break;cp=(cp<<6)|(p[i]&63);}
        if(i<=need){dst[out++]='?';++p;continue;}
        if((need==2&&cp<0x800UL)||(need==3&&cp<0x10000UL)||
           (cp>=0xd800UL&&cp<=0xdfffUL)||cp>0x10ffffUL){dst[out++]='?';p+=need+1;continue;}
        if(cp==0x2026UL){if(out+3>=capacity)break;dst[out++]='.';dst[out++]='.';dst[out++]='.';}
        else dst[out++]=(char)dos_for(cp,codepage);
        p+=need+1;
    }
    dst[out]=0;return out;
}
